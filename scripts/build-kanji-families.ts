/**
 * Kanji families: N5–N2 kanji that share a part and an on-reading, like
 * 青 清 晴 静 精 (せい). The shared part is often a sound hint, so learning
 * them together makes new kanji guessable. Writes
 * content/kanji-groups/families.json.
 *
 *   npm run build:kanji-families
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { KANJI_BY_LEVEL } from "../src/lib/kanji-levels.generated";

const CONTENT = join(process.cwd(), "content");
const LEVELS = ["N5", "N4", "N3", "N2"] as const;
const STROKES = new Set(["｜", "ノ", "丶", "亅", "乙"]);
/** Kanji too common as building blocks to mark a sound family. */
const NOT_A_FAMILY = new Set(["一", "二", "十", "口", "日", "小", "大", "人", "木", "目", "田", "土", "月", "力", "八"]);
type Rec = { slug: string; type?: string; term?: string; data?: { on?: string[] } };
const load = (f: string) => JSON.parse(readFileSync(join(CONTENT, f), "utf8")).records as Rec[];

const bySlug = new Map<string, Rec>();
for (const f of ["legacy/01-items.json", "opendata/00-legacy-level-fixes.json", "opendata/01-kanji-n5.json", "opendata/03-kanji-n4.json", "opendata/05-kanji-n3.json", "opendata/07-kanji-n2.json"])
  for (const r of load(f)) bySlug.set(r.slug, { ...(bySlug.get(r.slug) ?? {}), ...r });
const on = new Map<string, string[]>();
for (const r of bySlug.values()) if (r.type === "kanji" && r.term && r.data?.on?.length) on.set(r.term, r.data.on);

const rank = new Map<string, number>();
LEVELS.forEach((l, i) => [...KANJI_BY_LEVEL[l]].forEach((k) => rank.set(k, i)));
const parts = JSON.parse(readFileSync(join(CONTENT, "kanji-parts", "kradfile.json"), "utf8")).parts as Record<string, string[]>;

// A family is a kanji K plus every kanji that contains K whole (K is a part, or all of K's
// parts are) and shares one of K's on-readings: 青 → 清 晴 静 精 (せい).
const partsOf = (k: string) => new Set((parts[k] ?? []).filter((p) => !STROKES.has(p)));
const contains = (x: string, k: string) => {
  if (x === k) return false;
  const px = new Set(parts[x] ?? []);
  if (px.has(k)) return true;
  const pk = [...partsOf(k)];
  return pk.length >= 2 && pk.every((p) => px.has(p)) && (parts[x] ?? []).length > (parts[k] ?? []).length;
};
const groups: { slug: string; part: string; reading: string; kanji: string[]; title: string; level: string }[] = [];
const seen = new Set<string>();
for (const k of rank.keys())
  for (const reading of NOT_A_FAMILY.has(k) ? [] : (on.get(k) ?? [])) {
    const members = [...rank.keys()].filter((x) => contains(x, k) && (on.get(x) ?? []).includes(reading));
    if (members.length < 2) continue;
    const kanji = [k, ...members.sort((a, b) => rank.get(a)! - rank.get(b)!)].slice(0, 6);
    const key = [...kanji].sort().join("");
    if (seen.has(key)) continue;
    seen.add(key);
    groups.push({
      slug: `family-u${k.codePointAt(0)!.toString(16)}-${reading.replace(/[^ぁ-ん]/g, "")}`,
      part: k,
      reading,
      kanji,
      title: `${k} family: ${reading}`,
      level: LEVELS[Math.max(...kanji.map((x) => rank.get(x)!))],
    });
  }
groups.sort((a, b) => LEVELS.indexOf(a.level as never) - LEVELS.indexOf(b.level as never) || b.kanji.length - a.kanji.length);
writeFileSync(
  join(CONTENT, "kanji-groups", "families.json"),
  JSON.stringify({ note: "Generated by scripts/build-kanji-families.ts: kanji sharing a part and an on-reading.", groups }, null, 1) + "\n",
);
console.log(`families.json: ${groups.length} families`);
