/**
 * Generate src/lib/kanji-levels.ts: the JLPT level of every kanji the app
 * teaches (N5–N2), merged from the old app's kanji, their level fixes, and
 * the open-data kanji lists. Display and audits use it to tell which kanji
 * a level's exam prints.
 *
 *   npm run build:kanji-levels
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const CONTENT = join(process.cwd(), "content");
const LEVELS = ["N5", "N4", "N3", "N2"] as const;
type Rec = { slug: string; type?: string; term?: string; jlpt_level?: string; status?: string };
const load = (f: string) => JSON.parse(readFileSync(join(CONTENT, f), "utf8")).records as Rec[];

const bySlug = new Map<string, Rec>();
for (const f of ["legacy/01-items.json", "opendata/00-legacy-level-fixes.json", "opendata/01-kanji-n5.json", "opendata/03-kanji-n4.json", "opendata/05-kanji-n3.json", "opendata/07-kanji-n2.json"])
  for (const r of load(f)) bySlug.set(r.slug, { ...(bySlug.get(r.slug) ?? {}), ...r });

const level = new Map<string, number>();
for (const r of bySlug.values()) {
  if (r.type !== "kanji" || !r.term || [...r.term].length !== 1) continue;
  const i = LEVELS.indexOf(r.jlpt_level as (typeof LEVELS)[number]);
  if (i < 0) continue;
  level.set(r.term, Math.min(level.get(r.term) ?? 9, i));
}
const lines = LEVELS.map((l, i) => `  ${l}: "${[...level].filter(([, v]) => v === i).map(([k]) => k).sort().join("")}",`);
writeFileSync(
  join(process.cwd(), "src", "lib", "kanji-levels.generated.ts"),
  `// Generated by scripts/build-kanji-levels.ts. Do not edit.\n/** Kanji first taught at each JLPT level. */\nexport const KANJI_BY_LEVEL = {\n${lines.join("\n")}\n} as const;\n`,
);
